<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasMany;

class Layanan extends Model
{
    use HasFactory;

    /**
     * The table associated with the model.
     *
     * @var string
     */
    protected $table = 'layanan';

    /**
     * The attributes that are mass assignable.
     *
     * @var array<int, string>
     */
    protected $fillable = [
        'nama_layanan',
        'harga_per_kg',
        'durasi',
        'deskripsi',
    ];

    /**
     * The attributes that should be cast.
     *
     * @var array<string, string>
     */
    protected $casts = [
        'harga_per_kg' => 'decimal:2',
    ];

    /**
     * Accessor for formatted Rupiah price.
     */
    public function getHargaRupiahAttribute(): string
    {
        return 'Rp ' . number_format((float) ($this->harga_per_kg ?? 0), 0, ',', '.');
    }

    /**
     * Scope to search layanan by keyword.
     */
    public function scopeCari(Builder $query, ?string $keyword): Builder
    {
        if ($keyword) {
            $query->where('nama_layanan', 'like', "%{$keyword}%")
                  ->orWhere('deskripsi', 'like', "%{$keyword}%");
        }
        return $query;
    }

    /**
     * Total revenue generated by this service from paid transactions.
     */
    public function totalPendapatan(): float
    {
        return (float) $this->transaksis()->where('status_pembayaran', 'Lunas')->sum('total_harga');
    }

    /**
     * Get the transactions for the laundry service.
     */
    public function transaksis(): HasMany
    {
        return $this->hasMany(Transaksi::class, 'layanan_id');
    }
}
